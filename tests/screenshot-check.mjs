/**
 * PhishGuard — screenshot scanner regression checks.
 *
 * Covers the three findings recorded in IMPLEMENTATION-ISSUES.md:
 *   1. QR URLs are not analyzed twice.
 *   2. Per-flag source attribution is visible in the results UI.
 *   3. The tab indicator moves to the Screenshot tab.
 *
 * Run with the dev server already listening on the port below:
 *   npm run dev
 *   npm run test:screenshot
 *
 * Override the target with PHISHGUARD_URL (default http://localhost:5173).
 */

import { chromium } from 'playwright';

const TARGET = process.env.PHISHGUARD_URL || 'http://localhost:5173';
const OCR_WAIT_MS = 45_000;

let failures = 0;

function check(label, actual, expected) {
  const pass = actual === expected;
  if (!pass) failures += 1;
  console.log(`${pass ? 'PASS' : 'FAIL'}  ${label}`);
  console.log(`        expected: ${expected}`);
  console.log(`        actual:   ${actual}`);
  return pass;
}

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage();

const pageErrors = [];
page.on('pageerror', (err) => pageErrors.push(err.message));

try {
  await page.goto(TARGET, { waitUntil: 'networkidle' });
  await page.waitForTimeout(1200);

  // ---------------------------------------------------------------- issue 3
  // The tab indicator must track the active tab, including Screenshot.
  const indicatorBefore = await page.$eval('#tabIndicator', (el) => el.style.transform);
  await page.click('#tabScreenshot');
  await page.waitForTimeout(400);
  const indicatorAfter = await page.$eval('#tabIndicator', (el) => el.style.transform);
  const screenshotTab = await page.$eval('#tabScreenshot', (el) => ({
    left: el.offsetLeft,
    width: el.offsetWidth,
  }));

  console.log('\n--- Issue 3: tab indicator ---');
  check('indicator moves off the URL tab', indicatorBefore !== indicatorAfter, true);
  check(
    'indicator aligns with the Screenshot button',
    indicatorAfter,
    `translateX(${screenshotTab.left - 6}px)`
  );

  // ---------------------------------------------------------------- issues 1 + 2
  // The QR demo embeds a real QR code (generated by the `qrcode` package),
  // so this exercises the QR decode path end to end.
  console.log('\n--- Issues 1 + 2: QR decode, dedup, source attribution ---');
  const demoButtons = await page.$$('#screenshotExamples .example-chip');
  if (demoButtons.length < 2) throw new Error('QR demo chip not found');
  await demoButtons[1].click();

  await page.waitForTimeout(OCR_WAIT_MS);

  const qrDecoded = await page.$eval('#qrSection', (el) => el.style.display !== 'none');
  const qrPayload = await page.$eval('#qrContent', (el) => el.value);
  check('QR code decoded from the demo image', qrDecoded, true);
  console.log(`        payload: ${qrPayload}`);

  const linkInputs = await page.$$('.link-url-input');
  // The QR payload is also printed as text in the demo image, so OCR finds it
  // too. It must still be listed exactly once.
  check('QR URL listed exactly once (not twice)', linkInputs.length, 1);

  await page.click('#scanExtractedBtn');
  await page.waitForTimeout(5000);

  const flagCards = await page.$$('.flag-card');
  const flags = [];
  for (const card of flagCards) {
    flags.push({
      name: await card.$eval('.flag-name', (el) => el.textContent),
      severity: await card.$eval('.severity-badge', (el) => el.textContent),
      source: await card.$eval('.flag-source', (el) => el.textContent).catch(() => null),
    });
  }

  console.log('\n  rendered flags:');
  flags.forEach((f, i) => {
    console.log(`    ${i}. ${f.name} [${f.severity}] source=${f.source ?? '(none)'}`);
  });

  const flagsWithSource = flags.filter((f) => f.source);
  check('every screenshot flag carries a source label', flagsWithSource.length, flags.length);

  const urlSourced = flags.filter((f) => f.source?.startsWith('URL:'));
  const messageSourced = flags.filter((f) => f.source === 'Message text');
  check('flags are split between message text and URL sources', messageSourced.length > 0 && urlSourced.length > 0, true);

  // Each analysed URL contributes its own flags exactly once. The URL engine
  // raises 2 flags for a typosquatted domain; a double analysis would raise 4.
  const distinctUrlSources = new Set(urlSourced.map((f) => f.source));
  check('only one URL is analysed (no duplicate QR analysis)', distinctUrlSources.size, 1);
  check('URL flags are not duplicated', urlSourced.length, 2);

  // ---------------------------------------------------------------- regression
  console.log('\n--- Regression: existing paste-and-scan flows still work ---');
  await page.click('#tabUrl');
  await page.waitForTimeout(300);
  const urlChips = await page.$$('#urlExamples .example-chip');
  await urlChips[1].click(); // google.com
  await page.waitForTimeout(3000);
  const urlVerdict = await page.$eval('#gaugeVerdict', (el) => el.textContent);
  check('URL scan still resolves', urlVerdict, 'Safe / Verified');

  await page.click('#tabMessage');
  await page.waitForTimeout(300);
  const messageChips = await page.$$('#messageExamples .example-chip');
  await messageChips[2].click(); // normal message
  await page.waitForTimeout(3000);
  const messageVerdict = await page.$eval('#gaugeVerdict', (el) => el.textContent);
  check('Message scan still resolves', messageVerdict, 'Safe / Verified');

  console.log('\n--- Uncaught page errors ---');
  check('no uncaught page errors', pageErrors.length, 0);
  if (pageErrors.length) pageErrors.forEach((e) => console.log(`        ${e}`));
} catch (error) {
  failures += 1;
  console.error('\nFATAL:', error.message);
} finally {
  await browser.close();
}

console.log(`\n${failures === 0 ? 'ALL CHECKS PASSED' : `${failures} CHECK(S) FAILED`}`);
process.exit(failures === 0 ? 0 : 1);
